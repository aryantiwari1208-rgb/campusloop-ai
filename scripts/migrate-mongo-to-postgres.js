"use strict";

require("dotenv").config();
const { MongoClient } = require("mongodb");
const { Pool } = require("pg");

const mongoUri = process.env.MONGODB_URI;
const postgresUrl = process.env.DATABASE_URL || process.env.SUPABASE_DB_URL;

function requireValue(value, name) {
    if (!value) throw new Error(`${name} must be configured in the environment.`);
    return value;
}

function requiredText(value, field, collection) {
    if (typeof value !== "string" || value.length === 0) {
        throw new Error(`Cannot migrate ${collection}: a record has no valid ${field}.`);
    }
    return value;
}

function requiredId(value, collection) {
    const id = Number(value);
    if (!Number.isSafeInteger(id) || id < 1) {
        throw new Error(`Cannot migrate ${collection}: record ID ${String(value)} is not a positive integer.`);
    }
    return id;
}

function requiredDate(value, collection) {
    const date = value instanceof Date ? value.toISOString().slice(0, 10) : String(value || "");
    if (!/^\d{4}-\d{2}-\d{2}$/.test(date) || Number.isNaN(Date.parse(`${date}T00:00:00Z`))) {
        throw new Error(`Cannot migrate ${collection}: date ${date || "(empty)"} is invalid.`);
    }
    return date;
}

async function ensureSchema(client) {
    await client.query(`
        CREATE TABLE IF NOT EXISTS users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            email TEXT NOT NULL UNIQUE,
            password_hash TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
        CREATE TABLE IF NOT EXISTS products (
            id BIGINT PRIMARY KEY, name TEXT NOT NULL, category TEXT NOT NULL,
            price NUMERIC NOT NULL, icon TEXT NOT NULL, description TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS events (
            id BIGINT PRIMARY KEY, title TEXT NOT NULL, date DATE NOT NULL,
            location TEXT NOT NULL, category TEXT NOT NULL
        );
    `);
}

async function migrate() {
    requireValue(mongoUri, "MONGODB_URI");
    requireValue(postgresUrl, "DATABASE_URL");

    const mongo = new MongoClient(mongoUri);
    const pool = new Pool({ connectionString: postgresUrl });
    let pgClient;
    try {
        await mongo.connect();
        const source = mongo.db(process.env.MONGODB_DATABASE || "campusloop");
        pgClient = await pool.connect();
        await ensureSchema(pgClient);

        const users = await source.collection("users").find({}).toArray();
        const products = await source.collection("products").find({}).toArray();
        const events = await source.collection("events").find({}).toArray();

        await pgClient.query("BEGIN");
        for (const user of users) {
            const email = requiredText(user.email, "email", "users").trim().toLowerCase();
            const passwordHash = requiredText(user.passwordHash, "passwordHash", "users");
            const createdAt = user.createdAt instanceof Date ? user.createdAt : new Date(user.createdAt || Date.now());
            if (Number.isNaN(createdAt.getTime())) throw new Error("Cannot migrate users: a record has an invalid createdAt date.");
            await pgClient.query(
                `INSERT INTO users (name,email,password_hash,created_at) VALUES ($1,$2,$3,$4)
                 ON CONFLICT (email) DO UPDATE SET name=EXCLUDED.name,password_hash=EXCLUDED.password_hash,created_at=EXCLUDED.created_at`,
                [requiredText(user.name, "name", "users"), email, passwordHash, createdAt]
            );
        }

        for (const product of products) {
            const id = requiredId(product.id ?? product._id, "products");
            const price = Number(product.price);
            if (!Number.isFinite(price) || price < 0) throw new Error(`Cannot migrate products: product ${id} has an invalid price.`);
            await pgClient.query(
                `INSERT INTO products (id,name,category,price,icon,description) VALUES ($1,$2,$3,$4,$5,$6)
                 ON CONFLICT (id) DO UPDATE SET name=EXCLUDED.name,category=EXCLUDED.category,price=EXCLUDED.price,icon=EXCLUDED.icon,description=EXCLUDED.description`,
                [id, requiredText(product.name, "name", "products"), requiredText(product.category, "category", "products"), price,
                    typeof product.icon === "string" ? product.icon : "", typeof product.description === "string" ? product.description : ""]
            );
        }

        for (const event of events) {
            const id = requiredId(event.id ?? event._id, "events");
            await pgClient.query(
                `INSERT INTO events (id,title,date,location,category) VALUES ($1,$2,$3,$4,$5)
                 ON CONFLICT (id) DO UPDATE SET title=EXCLUDED.title,date=EXCLUDED.date,location=EXCLUDED.location,category=EXCLUDED.category`,
                [id, requiredText(event.title, "title", "events"), requiredDate(event.date, "events"),
                    requiredText(event.location, "location", "events"), requiredText(event.category, "category", "events")]
            );
        }

        await pgClient.query("COMMIT");
        console.log(`MongoDB migration complete: ${users.length} users, ${products.length} products, ${events.length} events copied.`);
        console.log("Users will need to sign in again; session records are not migrated.");
    } catch (error) {
        if (pgClient) {
            try { await pgClient.query("ROLLBACK"); } catch {}
        }
        console.error("Migration stopped:", error.message);
        process.exitCode = 1;
    } finally {
        if (pgClient) pgClient.release();
        await Promise.allSettled([mongo.close(), pool.end()]);
    }
}

migrate().catch(error => {
    console.error("Migration stopped:", error.message);
    process.exitCode = 1;
});
